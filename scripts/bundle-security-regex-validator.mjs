import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);

/** Produce a self-contained C++ resource so direct xmake builds need no runtime JS files. */
export async function buildSecurityRegexValidator() {
	const packagePath = require.resolve("@eslint-community/regexpp/package.json");
	const dependency = JSON.parse(await readFile(packagePath, "utf8"));
	const license = await readFile(join(dirname(packagePath), "LICENSE"), "utf8");
	const result = await build({
		absWorkingDir: projectRoot,
		entryPoints: ["scripts/security-regex-validator/entry.mjs"],
		bundle: true,
		platform: "neutral",
		format: "iife",
		globalName: "PiDeckSecurityRegex",
		target: "es2015",
		charset: "ascii",
		minify: true,
		write: false,
		// Preserve the dependency notice inside the compiled binary too.
		banner: { js: `/*! @eslint-community/regexpp ${dependency.version}\n${license}*/` },
	});
	const bundle = result.outputFiles[0].text;
	// Keep each literal below MSVC's single-string size limit.
	const chunks = [];
	for (let offset = 0; offset < bundle.length; offset += 2048) {
		chunks.push(`    ${JSON.stringify(bundle.slice(offset, offset + 2048))}`);
	}
	const header = [
		"// Generated by scripts/bundle-security-regex-validator.mjs. Do not edit.",
		`// ECMAScript syntax validation from @eslint-community/regexpp ${dependency.version}.`,
		"#pragma once",
		"",
		"namespace security::internal {",
		"inline constexpr char kSecurityRegexValidatorSource[] =",
		`${chunks.join("\n")};`,
		"} // namespace security::internal",
		"",
	].join("\n");
	return { bundle, header, headerPath: join(projectRoot, "native/backend/SecurityRegexValidatorSource.h") };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const { header, headerPath } = await buildSecurityRegexValidator();
	const existing = await readFile(headerPath, "utf8").catch((error) => {
		if (error.code === "ENOENT") return "";
		throw error;
	});
	if (process.argv.includes("--check")) {
		if (existing !== header) {
			throw new Error("Security regex validator is stale. Run npm run build:security-regex-validator.");
		}
	} else if (existing !== header) {
		await writeFile(headerPath, header, "utf8");
	}
}
