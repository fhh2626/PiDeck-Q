import { readFile, writeFile } from "node:fs/promises";

if (!process.versions.node.startsWith("22.") || process.versions.unicode !== "16.0") {
	throw new Error("Run this generator with Node 22.19.0 (Unicode 16.0).");
}

/** Encode sorted inclusive ranges as base-36 gap/width pairs (end minus start). */
function rangesFor(property) {
	const ranges = [];
	let previousEnd = -1;
	for (let start = 0; start <= 0x10ffff; start++) {
		if (!property.test(String.fromCodePoint(start))) continue;
		let end = start;
		while (end < 0x10ffff && property.test(String.fromCodePoint(end + 1))) end++;
		ranges.push(`${(start - previousEnd - 1).toString(36)} ${(end - start).toString(36)}`);
		previousEnd = end;
		start = end;
	}
	const lines = [];
	for (let i = 0; i < ranges.length; i += 16) {
		const chunk = ranges.slice(i, i + 16).join(" ");
		lines.push(i + 16 < ranges.length ? `\t"${chunk} " +` : `\t"${chunk}";`);
	}
	return lines.join("\n");
}

const output = new URL("../../src/shared/securityRegexUnicode16.ts", import.meta.url);
const source = [
	"// Generated by scripts/security-regex-validator/generate-unicode16.mjs. Do not edit.",
	"// Unicode 16.0 ID_Start and ID_Continue ranges from Node 22.",
	"// Unicode data: https://www.unicode.org/license.txt",
	"export const ID_START_RANGES =",
	rangesFor(/^\p{ID_Start}$/u),
	"",
	"export const ID_CONTINUE_RANGES =",
	rangesFor(/^\p{ID_Continue}$/u),
	"",
].join("\n");
if (process.argv.includes("--check")) {
	if (await readFile(output, "utf8") !== source) throw new Error("The Unicode 16 range table is stale.");
} else {
	await writeFile(output, source, "utf8");
}
